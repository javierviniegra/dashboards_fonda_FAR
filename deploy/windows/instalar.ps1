# deploy/windows/instalar.ps1
#
# FIRST-TIME installation of Dashboards Fonda on the production app VM
# (SVR-HIKCENTER), the same steps used for Central de Reportes, in one script.
# Run it ONCE, in an ADMINISTRATOR PowerShell, from the cloned folder:
#
#   cd C:\Apps
#   git clone --recurse-submodules https://github.com/javierviniegra/dashboards_fonda_FAR.git DashboardsFonda
#   cd DashboardsFonda
#   Set-ExecutionPolicy -ExecutionPolicy RemoteSigned -Scope CurrentUser   # once, if scripts are blocked
#   .\deploy\windows\instalar.ps1
#
# Before: run deploy\sql\create_dashboards_fonda_db.sql as root on 187.251.203.223.
# After: add the Apache lines of docs\PRODUCTION_SETUP.md (step 5).
#
# What it does:
#   1. virtualenv + dependencies;
#   2. config\.env: a new secret key; this app's database (asks its password);
#      the READ-ONLY sources copied from Central de Reportes' production .env on
#      this VM (Wansoft, Presupuestos AP, Odoo; Central's DB host for the CEDIS
#      mapping); never printed. An existing config\.env is never overwritten;
#   3. deploy\update.ps1 (submodule, migrations, branches, static, Waitress on 8045);
#   4. your administrator user (asks for it);
#   5. the three scheduled tasks (startup, daily update 05:30, warm-up).
#
# ASCII only on purpose: Windows PowerShell 5.1 reads .ps1 files as ANSI.

param([string]$CentralEnv = "C:\Apps\CentralDeReportes\config\.env")

$ErrorActionPreference = "Stop"
$ProjectDir = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
Set-Location $ProjectDir
$EnvFile = Join-Path $ProjectDir "config\.env"
$Python = Join-Path $ProjectDir ".venv\Scripts\python.exe"

$esAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole(
    [Security.Principal.WindowsBuiltInRole]::Administrator)
if (-not $esAdmin) { throw "Abre PowerShell como administrador (las tareas programadas lo necesitan)." }
if (-not (Test-Path (Join-Path $ProjectDir "vendor\central\central\motor"))) {
    Write-Host "=== Bajando el motor de Central (submodulo) ==="
    git submodule update --init --force
}

Write-Host "=== 1. Entorno virtual y dependencias ==="
if (-not (Test-Path $Python)) { python -m venv .venv }
& $Python -m pip install --upgrade pip
& $Python -m pip install -r requirements.txt

Write-Host "=== 2. config\.env ==="
if (Test-Path $EnvFile) {
    Write-Host "config\.env ya existe: no se toca."
} else {
    if (-not (Test-Path $CentralEnv)) { throw "No encuentro el .env de Central en $CentralEnv (usa -CentralEnv <ruta>)." }
    $central = @{}
    foreach ($linea in Get-Content $CentralEnv -Encoding UTF8) {
        if ($linea -match '^\s*([A-Za-z0-9_]+)\s*=(.*)$') { $central[$Matches[1]] = $Matches[2].Trim() }
    }
    $seguro = Read-Host "Contrasena de la base dashboards_fonda (la que pusiste en el SQL)" -AsSecureString
    $clave = [Runtime.InteropServices.Marshal]::PtrToStringAuto([Runtime.InteropServices.Marshal]::SecureStringToBSTR($seguro))
    $secreto = & $Python -c "from django.core.management.utils import get_random_secret_key as g; print(g())"
    $hostBd = $central["EJECUTIVOS_DB_HOST"]
    $valores = [ordered]@{
        "ENV" = "prod"; "FUENTES_ENV" = "prod"; "DJANGO_SECRET_KEY" = $secreto; "DJANGO_DEBUG" = "false"
        "DJANGO_ALLOWED_HOSTS" = "187.251.203.223,192.168.100.93,localhost,127.0.0.1"
        "DJANGO_FORCE_SCRIPT_NAME" = "/dashboards_fonda"; "DJANGO_SECURE_COOKIES" = "false"
        "DJANGO_CSRF_TRUSTED_ORIGINS" = "http://187.251.203.223:8088"
        "DASHBOARDS_DB_HOST" = $hostBd; "DASHBOARDS_DB_PORT" = "3306"; "DASHBOARDS_DB_USER" = "dashboards_fonda"
        "DASHBOARDS_DB_PASSWORD" = $clave; "DASHBOARDS_DB_NAME" = "dashboards_fonda"
        "CENTRAL_DB_HOST" = $hostBd; "CENTRAL_DB_PORT" = "3306"; "CENTRAL_DB_USER" = "dashboards_fonda"
        "CENTRAL_DB_PASSWORD" = $clave; "CENTRAL_DB_NAME" = $central["EJECUTIVOS_DB_NAME"]
    }
    foreach ($k in @("WANSOFT_DB_HOST", "WANSOFT_DB_USER", "WANSOFT_DB_PASSWORD", "WANSOFT_DB_NAME",
                     "PRESUPUESTOS_DB_HOST", "PRESUPUESTOS_DB_PORT", "PRESUPUESTOS_DB_USER", "PRESUPUESTOS_DB_PASSWORD",
                     "PRESUPUESTOS_DB_NAME", "ODOO_URL", "ODOO_DB_NAME", "ODOO_USER", "ODOO_PASSWORD")) {
        $valores[$k] = $central[$k]
        if ($k -like "*_PORT" -and -not $valores[$k]) { $valores[$k] = "3306" }
    }
    $faltan = @($valores.Keys | Where-Object { -not $valores[$_] -and $_ -ne "DJANGO_SECURE_COOKIES" })
    if ($faltan.Count) { throw ("Faltan valores (revisa el .env de Central): " + ($faltan -join ", ")) }
    $lineas = @("# Generated by deploy\windows\instalar.ps1 on $(Get-Date -Format yyyy-MM-dd). Never commit it.")
    foreach ($k in $valores.Keys) { $lineas += "$k=$($valores[$k])" }
    [IO.File]::WriteAllLines($EnvFile, $lineas, (New-Object Text.UTF8Encoding($false)))
    Write-Host "config\.env creado (valores no mostrados)."
}

Write-Host "=== 3. Primera actualizacion (motor, migraciones, sucursales, estaticos, servidor) ==="
& (Join-Path $ProjectDir "deploy\update.ps1")

Write-Host "=== 4. Tu usuario administrador ==="
& $Python manage.py createsuperuser

Write-Host "=== 5. Tareas programadas ==="
& (Join-Path $PSScriptRoot "registrar_tareas.ps1")

Write-Host ""
Write-Host "Listo en la VM. Falta Apache (docs\PRODUCTION_SETUP.md, paso 5) y abrir"
Write-Host "http://187.251.203.223:8088/dashboards_fonda/"
